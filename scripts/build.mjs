// @ts-strict
/**
 * 游戏雷达 Game Radar - 构建器（绿地阶段 0）
 *
 * 两种产物策略（按语义忠实度选择）：
 *   1. **页面 bundle = 顺序 concat + esbuild transform**——classic 脚本的
 *      全局作用域顺序执行语义与浏览器多 <script> 100% 等价；esbuild bundle
 *      会按 ESM import 边摇树/重命名裸标识符（实测丢 5 模块 + loadStats
 *      ReferenceError），故页面侧禁用 bundle 语义。
 *   2. **content/background = esbuild bundle**——content 的 16 模块是真 ESM
 *      import 图（module-loaders 桥的相对路径动态 import）；background 全
 *      ESM 静态图。classic 注入序列（patterns/msg/escape/adapters）用 concat
 *      前置，避免被 ESM 语义误处理。
 *
 * 装载桥：content/module-loaders.js（构建器生成）——tracker 用 __GR_BUNDLE__
 * define 双模式切换（bundle 内静态相对 import 内联；源模式 getURL 绝对路径）。
 *
 * Stage-0 builder: pages are order-preserving concatenations (classic global
 * scope semantics); content/background use esbuild bundling for real ESM graphs.
 */
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const warn = [];

/** @param {string} p @returns {string} */
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf-8');
/** @param {string} p @returns {string[]} */
const listDir = (p) => fs.readdirSync(p, { withFileTypes: true }).map((e) => e.name);
/** @param {string} p @returns {boolean} */
const exists = (p) => fs.existsSync(path.join(ROOT, p));

// ============ 1) content/module-loaders.js 生成（装载桥） ============

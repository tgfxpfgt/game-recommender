/** @param {string} htmlPath @returns {string[]} 本地 .js 清单（HTML 顺序） */
function parsePageScripts(htmlPath) {
  const html = read(htmlPath);
  const out = [];
  const re = /<script\s+([^>]*)>\s*<\/script>/g;
  for (const m of html.matchAll(re)) {
    const attrs = m[1];
    const srcM = attrs.match(/src="([^"]+)"/);
    if (!srcM || /^https?:\/\//.test(srcM[1])) continue;
    out.push({ src: srcM[1], isModule: /type=["']module["']/.test(attrs) });
  }
  return out;
}

/** @param {string} page @returns {{html: string, cssFiles: string[], bundleName: string}} */
function concatPage(page) {
  const htmlPath = `${page}/${page}.html`;
  const scripts = parsePageScripts(htmlPath);
  if (scripts.length === 0) throw new Error(`${htmlPath} 未找到本地 script`);
  const bundleName = `${page}.bundle.js`;
  const parts = [];
  for (const { src, isModule } of scripts) {
    // HTML 里的 src 相对页面目录解析
    const abs = path.posix.normalize(path.posix.join(page, src));
    if (!exists(abs)) throw new Error(`${htmlPath} 引用缺失: ${abs}`);
    const body = `/* ===== ${abs} ===== */\n` + read(abs);
    if (isModule && src.endsWith('.mjs')) {
      // v14.33.1：type="module" 引用的 .mjs 组件（preact 组件——裸包依赖）不并入
      // classic bundle：transformSync 无 bundle 能力，裸 import 会被转成 require()
      // 泄漏进 classic 上下文（v15 阶段 3 遗留缺陷——页面 console ReferenceError
      // + 与独立 module tag 双重执行）。产物走下方 .mjs 随页 bundle 分支
      //（preact 内联、format=esm），HTML 折叠保持独立 type=module tag 引用之。
      continue;
    }
    if (isModule) {
      // v15：type="module" 引用的 .js ESM 共享脚本（如 fm-keys.js 的 export +
      // globalThis 副作用挂载）——export 语句在 classic 上下文是 SyntaxError
      //（整 bundle 零执行的实锤根因），单独 transform 为 iife：export 被消化、
      // globalThis 副作用保留、无依赖单文件转换安全。
      const modRes = esbuild.transformSync(body, {
        loader: 'js',
        format: 'iife',
        target: ['chrome109'],
        charset: 'utf8'
      });
      parts.push(modRes.code);
    } else {
      parts.push(body);
    }
  }
  const concat = parts.join('\n;\n') + '\n';
  // esbuild transform：语法合法性校验 + 目标语义降级（不改结构、不摇树、不重命名）
  const res = esbuild.transformSync(concat, { loader: 'js', target: ['chrome109'], charset: 'utf8' });
  // HTML 改写：本地 script 序列折叠为单 bundle tag（首个标签位置；正则与
  // parsePageScripts 同款——含 type="module" 形态，否则 fm-keys 类标签漏折叠）
  const scriptRe = /<script\s+([^>]*)>\s*<\/script>\s*/g;
  let first = true;
  /** @type {string[]} */
  const moduleTags = []; // v15 阶段 3：type=module 脚本保持独立 tag（真 ESM 动态 import 链）
  let html = read(htmlPath).replace(scriptRe, (m0, attrs) => {
    const srcM = attrs.match(/src="([^"]+)"/);
    if (!srcM || /^https?:\/\//.test(srcM[1])) return m0;
    if (/type=["']module["']/.test(attrs)) {
      moduleTags.push(`<script type="module" src="${srcM[1]}"></script>`);
      return '';
    }
    if (first) {
      first = false;
      return `<script src="${bundleName}"></script>\n`;
    }
    return '';
  });
  // module tags 追加到 bundle tag 后（保持 HTML 缩进）
  if (moduleTags.length > 0) {
    html = html.replace(
      `<script src="${bundleName}"></script>`,
      `<script src="${bundleName}"></script>\n    ` + moduleTags.join('\n    ')
    );
  }
  // v15 修正：收集**全部本地引用资源**（link href / img src——属性顺序任意，
  // 原正则要求 rel 紧邻 href 导致 type 插入时漏收集 → options.css 等 404）。
  // 仅收静态资产（.js 已打包进 bundle）。
  const assets = [];
  const refRe = /(?:<link[^>]*?href="|<img[^>]*?src=")([^"]+)"/g;
  for (const m of read(htmlPath).matchAll(refRe)) {
    const href = m[1];
    if (/^https?:/.test(href) || href.startsWith('data:')) continue;
    const abs = path.posix.normalize(path.posix.join(path.dirname(htmlPath), href.split('?')[0].split('#')[0]));
    if (abs.endsWith('.js')) continue;
    if (!assets.includes(abs)) assets.push(abs);
  }
  return { html, cssFiles: assets, bundleName, code: res.code };
}

/** 内容 classic 注入序列 + ESM 管线 bundle */
function buildContent() {
  // classic 序列（源 manifest content_scripts js 序，去 tracker——tracker 走 ESM bundle）
  const classicSeq = [
    'shared/patterns.js',
    'shared/msg.js',
    'shared/escape.js',
    'adapters/default.js',
    'adapters/sites/xdgame.js',
    'adapters/sites/xianyudanji.js',
    'adapters/sites/gamer520.js',
    'adapters/sites/3dmgame.js',
    'adapters/sites/ali213.js',
    'adapters/sites/gamersky.js',
    'adapters/index.js'
  ];
  const classicParts = [];
  for (const s of classicSeq) {
    if (!exists(s)) throw new Error(`content 注入序列缺失: ${s}`);
    classicParts.push(`/* ===== ${s} ===== */\n` + read(s));
  }
  const classic = classicParts.join('\n;\n') + '\n;\n';
  const esmRes = esbuild.buildSync({
    entryPoints: [path.join(ROOT, 'content/tracker.js')],
    bundle: true,
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    logLevel: 'silent',
    charset: 'utf8',
    target: ['chrome109'],
    format: 'iife',
    // banner 注入双模式开关（const 词法声明在 iife 外层作用域，typeof 检查安全
    // ——不用 define：define 会跳过 typeof 表达式导致源码形态替换失败）
    banner: { js: 'const __GR_BUNDLE__ = true;' },
    write: false
  });
  if (esmRes.errors.length > 0) {
    throw new Error('content ESM bundle 失败: ' + esmRes.errors.map((e) => e.text).join('; '));
  }
  return classic + esmRes.outputFiles[0].text;
}

async function buildBackground() {
  const res = await esbuild.build({
    entryPoints: [path.join(ROOT, 'background/service-worker.js')],
    bundle: true,
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    logLevel: 'silent',
    charset: 'utf8',
    target: ['chrome109'],
    format: 'esm',
    // banner 注入打包模式清单：自定义站点动态注册只挂 tracker bundle 单文件
    //（classic 注入序列已内联进该 bundle——源 7 文件在 dist 不存在）
    banner: { js: 'const __GR_SITE_SCRIPTS__ = ["content/tracker.js"];' },
    write: false
  });
  if (res.errors.length > 0) {
    throw new Error('background bundle 失败: ' + res.errors.map((e) => e.text).join('; '));
  }
  return res.outputFiles[0].text;
}

// ============ 3) dist 镜像组装 ============
/** @param {string} src @param {string} dest */
function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const name of listDir(src)) {
    const s = path.join(src, name);
    const d = path.join(dest, name);
    if (fs.statSync(s).isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

/** dist manifest：content_scripts 折叠单文件 + WAR 收窄（qr 库保留运行时装载） */
function buildManifest() {
  const manifest = JSON.parse(read('manifest.json'));
  for (const cs of manifest.content_scripts || []) {
    cs.js = ['content/tracker.js'];
  }
  if (manifest.web_accessible_resources?.length) {
    manifest.web_accessible_resources = manifest.web_accessible_resources.map((war) => ({
      ...war,
      resources: war.resources.filter((r) => r.startsWith('lib/'))
    }));
  }
  return manifest;
}

async function assembleDist() {
  fs.mkdirSync(DIST, { recursive: true });
  for (const dir of ['_locales', 'icons', 'styles', 'lib']) {
    if (fs.existsSync(path.join(ROOT, dir))) copyDir(path.join(ROOT, dir), path.join(DIST, dir));
  }
  const cssCopied = new Set();
  for (const page of PAGES) {
    const htmlPath = `${page}/${page}.html`;
    if (!exists(htmlPath)) continue;
    const { html, cssFiles, bundleName, code } = concatPage(page);
    fs.mkdirSync(path.join(DIST, page), { recursive: true });
    fs.writeFileSync(path.join(DIST, htmlPath), html, 'utf-8');
    fs.writeFileSync(path.join(DIST, page, bundleName), code, 'utf-8');
    // v15 阶段 3：type=module 页面脚本（.mjs preact 组件）随页复制
    for (const { src: sc, isModule: im } of parsePageScripts(htmlPath)) {
      if (!im) continue;
      const absSrc = path.posix.normalize(path.posix.join(page, sc));
      if (!exists(absSrc)) continue;
      fs.mkdirSync(path.dirname(path.join(DIST, absSrc)), { recursive: true });
      // esbuild bundle（裸包名 import 在扩展页面无法解析——内联 preact/hooks）
      const mres = esbuild.buildSync({
        entryPoints: [path.join(ROOT, absSrc)],
        bundle: true,
        minify: false,
        sourcemap: false,
        legalComments: 'none',
        logLevel: 'silent',
        charset: 'utf8',
        target: ['chrome109'],
        format: 'esm',
        write: false
      });
      if (mres.errors.length > 0) {
        throw new Error('module 页面脚本 bundle 失败: ' + absSrc + ' — ' + mres.errors.map((e) => e.text).join('; '));
      }
      fs.writeFileSync(path.join(DIST, absSrc), mres.outputFiles[0].text, 'utf-8');
    }
    for (const css of cssFiles) {
      if (cssCopied.has(css)) continue;
      cssCopied.add(css);
      if (!exists(css)) {
        warn.push(`CSS 缺失: ${css}`);
        continue;
      }
      fs.mkdirSync(path.dirname(path.join(DIST, css)), { recursive: true });
      fs.copyFileSync(path.join(ROOT, css), path.join(DIST, css));
    }
  }
  fs.writeFileSync(path.join(DIST, 'manifest.json'), JSON.stringify(buildManifest(), null, 2) + '\n', 'utf-8');
  console.log(`✓ dist 镜像组装完成（静态目录 4 + 页面 ${PAGES.length} + manifest）`);
}

function verifyDist() {
  const must = [
    'dist/manifest.json',
    'dist/background/service-worker.js',
    'dist/content/tracker.js',
    'dist/lib/vendor/qrcode-reader.js',
    'dist/_locales/zh_CN/messages.json',
    ...PAGES.map((p) => `dist/${p}/${p}.bundle.js`),
    ...PAGES.map((p) => `dist/${p}/${p}.html`)
  ];
  const missing = must.filter((f) => !fs.existsSync(path.join(ROOT, f)));
  if (missing.length > 0) throw new Error('dist 缺产物: ' + missing.join(', '));
  // 关键符号抽检（页面 concat 语义：全部 classic 函数必须在场）
  const probes = [
    ['dist/dashboard/dashboard.bundle.js', 'function loadStats'],
    ['dist/dashboard/dashboard.bundle.js', 'function exportTrendsCsv'],
    ['dist/dashboard/dashboard.bundle.js', 'function loadHealthCards'],
    ['dist/dashboard/dashboard.bundle.js', 'function loadTrends'],
    ['dist/content/tracker.js', 'MODULE_LOADERS'],
    ['dist/background/service-worker.js', 'early-message-router']
  ];
  const failed = probes.filter(([f, needle]) => !fs.readFileSync(path.join(ROOT, f), 'utf-8').includes(needle));
  if (failed.length > 0) {
    throw new Error('bundle 关键符号缺失: ' + failed.map(([f, n]) => `${f} ~ ${n}`).join(', '));
  }
  // v14.33.1 回归防线：classic concat bundle 禁 require(——type="module" 的 .mjs
  // 组件（裸包依赖）若被误并入，transformSync 会把裸 import 转 require 泄漏
  //（v15 阶段 3 遗留缺陷：popup/options/dashboard/hub console ReferenceError）
  const requireLeaks = PAGES.map((p) => `dist/${p}/${p}.bundle.js`).filter((f) =>
    fs.readFileSync(path.join(ROOT, f), 'utf-8').includes('require(')
  );
  if (requireLeaks.length > 0) {
    throw new Error('classic bundle 泄漏 require()（.mjs 组件误并入）: ' + requireLeaks.join(', '));
  }
  const srcManifest = JSON.parse(read('manifest.json'));
  const distManifest = JSON.parse(fs.readFileSync(path.join(DIST, 'manifest.json'), 'utf-8'));
  const srcWar = (srcManifest.web_accessible_resources || []).reduce((n, w) => n + (w.resources?.length || 0), 0);
  const distWar = (distManifest.web_accessible_resources || []).reduce((n, w) => n + (w.resources?.length || 0), 0);
  console.log(`✓ dist 自检通过（关键符号 6/6 · WAR ${srcWar} → ${distWar}）`);
}

